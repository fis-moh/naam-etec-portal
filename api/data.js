function normalizeStage(val) {
  const s = (val || '').trim();
  if (s.includes('ابتدائ')) return 'ابتدائي';
  if (s.includes('متوسط')) return 'متوسط';
  if (s.includes('ثانو')) return 'ثانوي';
  if (s.includes('مشترك')) return 'مشترك';
  return s || 'الكل';
}

async function fetchSheetCSV(sheetId, sheetName) {
  const urls = [
    `https://docs.google.com/spreadsheets/d/${sheetId}/gviz/tq?tqx=out:csv&sheet=${encodeURIComponent(sheetName)}`,
    `https://docs.google.com/spreadsheets/d/${sheetId}/export?format=csv&sheet=${encodeURIComponent(sheetName)}`
  ];
  for (const url of urls) {
    try {
      const resp = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0' } });
      if (resp.ok) {
        const text = await resp.text();
        if (text && !text.trim().startsWith('<!DOCTYPE') && !text.trim().startsWith('<html')) {
          return parseCSV(text);
        }
      }
    } catch (e) {}
  }
  return null;
}

function parseCSV(csvText) {
  const clean = csvText.replace(/^\uFEFF/, '').replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const rows = [];
  let row = [];
  let val = '';
  let inQuotes = false;

  for (let i = 0; i < clean.length; i++) {
    const c = clean[i];
    const next = clean[i + 1];
    if (c === '"') {
      if (inQuotes && next === '"') { val += '"'; i++; }
      else { inQuotes = !inQuotes; }
    } else if (c === ',' && !inQuotes) {
      row.push(val.trim()); val = '';
    } else if (c === '\n' && !inQuotes) {
      row.push(val.trim());
      if (row.some(cell => cell !== '')) rows.push(row);
      row = []; val = '';
    } else {
      val += c;
    }
  }
  if (val !== '' || row.length > 0) {
    row.push(val.trim());
    if (row.some(cell => cell !== '')) rows.push(row);
  }
  return rows;
}

